// 1) Входящий вебхук Битрикс24 с полными правами (с "/" на конце или без).
const B24_WEBHOOK = 'https://YOUR_PORTAL.bitrix24.ru/rest/1/xxxxxxxxxxxxxxxx/';

// 2) Как определять IP клиента (n8n обычно стоит за nginx).
//    'x-forwarded-for'  — берётся адрес, который дописал ваш прокси (защищено от подмены);
//    'x-real-ip'        — nginx: proxy_set_header X-Real-IP $remote_addr;
//    'cf-connecting-ip' — если перед сервером Cloudflare.
const IP_HEADER = 'x-forwarded-for';
//    Сколько доверенных прокси стоит перед n8n (только для x-forwarded-for):
//    nginx → n8n = 1;  Cloudflare → nginx → n8n = 2.
const PROXY_HOPS = 1;

// 3) Ключи интеграций.
//    key     — секрет интеграции, минимум 24 символа. Сгенерировать: openssl rand -hex 24
//    methods — по одному методу на строку. Можно маску: crm.lead.*   Всё подряд: *
//              batch отдельно указывать не нужно: он пропускается,
//              если ВСЕ команды внутри него разрешены этому ключу.
//    ips     — по одному IP или подсети на строку: 1.2.3.4, 10.0.0.0/24, 2a01:4f8::/32.
//              Пусто — доступ с любого IP.
//    enabled — false, чтобы временно отключить ключ (необязательно).
//    Строки, начинающиеся с #, — комментарии.
const KEYS = [
  {
    name: 'Сайт — заявки',
    key: 'CHANGE_ME',
    methods: `
      crm.lead.add
    `,
    ips: `
    `,
  },

  {
    name: 'Пример: телефония, только с сервера АТС',
    key: 'CHANGE_ME',
    methods: `
      crm.lead.add
      crm.lead.get
      crm.duplicate.findbycomm
      crm.activity.*
    `,
    ips: `
      203.0.113.10
      # 198.51.100.0/24
    `,
  },
];

// ---------------------------------------------------------------------
//  Ниже ничего менять не нужно.
// ---------------------------------------------------------------------
return [{
  json: {
    req: $input.first().json,
    cfg: { webhook: B24_WEBHOOK, ipHeader: IP_HEADER, proxyHops: PROXY_HOPS, keys: KEYS },
  },
}];
